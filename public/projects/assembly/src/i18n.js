const KEY = 'veresta-lang';

export function initialLang() {
  const param = new URLSearchParams(location.search).get('lang');
  if (param === 'ru' || param === 'en') return param;
  try {
    const saved = localStorage.getItem(KEY);
    if (saved === 'ru' || saved === 'en') return saved;
  } catch {
    // storage may be blocked; the default below still applies
  }
  return /^(ru|be|uk|kk)/i.test(navigator.language || 'ru') ? 'ru' : 'en';
}

export function applyLang(lang) {
  const t = texts[lang];
  document.documentElement.lang = lang;
  document.title = t['doc.title'];
  for (const el of document.querySelectorAll('[data-i18n]')) el.textContent = t[el.dataset.i18n];
  for (const el of document.querySelectorAll('[data-i18n-html]')) el.innerHTML = t[el.dataset.i18nHtml];
  for (const el of document.querySelectorAll('[data-i18n-alt]')) el.alt = t[el.dataset.i18nAlt];
  const sw = document.querySelector('[data-lang-switch]');
  sw.textContent = t['lang.switch'];
  sw.setAttribute('aria-label', t['lang.label']);
  try {
    localStorage.setItem(KEY, lang);
  } catch {
    // not being able to remember the choice is not an error
  }
}
