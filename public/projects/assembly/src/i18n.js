const KEY = 'veresta-lang';
const ROMAN = ['I', 'II', 'III', 'IV'];
let current = 'ru';

export const lang = () => current;

export function initialLang() {
  const param = new URLSearchParams(location.search).get('lang');
  if (param === 'ru' || param === 'en') return param;
  try {
    const saved = localStorage.getItem(KEY);
    if (saved === 'ru' || saved === 'en') return saved;
  } catch {
    // storage may be blocked; the default below still applies
  }
  return /^(ru|be|uk|kk)/i.test(navigator.language || 'ru') ? 'ru' : 'en';
}

export function t(key, vars) {
  let text = texts[current][key];
  if (vars) for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, value);
  return text;
}

// 14.9 -> "14,9" in Russian and "14.9" in English; trailing zeros are dropped.
export function num(value, digits = 1) {
  const text = Number(value.toFixed(digits)).toString();
  return current === 'ru' ? text.replace('.', ',') : text;
}

export const price = (mln) => t('money.mln', {v: num(mln, 2)});
export const thousands = (k) => t('money.k', {v: Math.round(k).toLocaleString(current === 'ru' ? 'ru-RU' : 'en-US')});

export function plural(n, forms) {
  if (current === 'en') return n === 1 ? forms.en[0] : forms.en[1];
  const a = n % 10;
  const b = n % 100;
  if (a === 1 && b !== 11) return forms.ru[0];
  return a >= 2 && a <= 4 && (b < 12 || b > 14) ? forms.ru[1] : forms.ru[2];
}

export const FLAT_FORMS = {ru: ['квартиру', 'квартиры', 'квартир'], en: ['apartment', 'apartments']};
export const YEAR_FORMS = {ru: ['год', 'года', 'лет'], en: ['year', 'years']};

// {q, year} to "IV кв. 2027" / "Q4 2027"; long: "IV квартал 2027".
export function quarterLabel({q, year}, long = false) {
  if (current === 'en') return `Q${q} ${year}`;
  return `${ROMAN[q - 1]} ${long ? 'квартал' : 'кв.'} ${year}`;
}

export function applyLang(next) {
  current = next;
  const dict = texts[next];
  document.documentElement.lang = next;
  document.title = dict['doc.title'];
  for (const el of document.querySelectorAll('[data-i18n]')) el.textContent = dict[el.dataset.i18n];
  for (const el of document.querySelectorAll('[data-i18n-html]')) el.innerHTML = dict[el.dataset.i18nHtml];
  for (const el of document.querySelectorAll('[data-i18n-alt]')) el.alt = dict[el.dataset.i18nAlt];
  for (const el of document.querySelectorAll('[data-i18n-label]')) el.setAttribute('aria-label', dict[el.dataset.i18nLabel]);
  for (const el of document.querySelectorAll('[data-lang-switch]')) {
    el.textContent = next === 'ru' ? 'EN' : 'RU';
    el.setAttribute('aria-label', dict['lang.label']);
  }
  try {
    localStorage.setItem(KEY, next);
  } catch {
    // not being able to remember the choice is not an error
  }
}
